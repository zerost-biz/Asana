// P1（プロジェクト追加・受注見込み・PJ化・配置・メンバー・スキルマップ・完了処理・管理・Reset・権限）のE2E
import { launch, goto, ok, num, summary, switchUser } from './lib.mjs'
const { browser, page, errs } = await launch()
const main = () => page.locator('main').innerText()
const col = (n) => page.locator(`.board__col[aria-label="${n}"]`)

// ---------- プロジェクトの追加（テンプレート） ----------
await goto(page, '/')
await page.getByRole('button', { name: 'プロジェクトを追加' }).first().click()
await page.getByLabel('プロジェクト名').fill('F社 E2E構想')
await page.getByRole('button', { name: /^追加|作成/ }).last().click()
await page.waitForURL(/\/projects\/p-.*\/wbs/)
await page.waitForTimeout(300)
ok('プロジェクト追加: 標準テンプレートの作業項目が入る（3フェーズ・計164h）', (await page.locator('.wbs__row--parent').count()) >= 3 && (await page.locator('.wbs__row--total').innerText()).includes('164'))
ok('プロジェクト追加: マイルストーン3件', (await page.locator('.wbs__row--ms').count()) === 3)
await goto(page, '/projects')
ok('プロジェクト追加: 一覧に出る', (await page.locator('a.pf__row', { hasText: 'F社 E2E構想' }).count()) === 1)

// ---------- 受注見込み ----------
await goto(page, '/pipeline')
ok('受注見込み: 5段階のボードと案件カード', (await page.locator('.board__col').count()) === 5 && (await page.locator('.ocard').count()) === 5)
await page.getByRole('button', { name: '案件を追加' }).click()
await page.getByLabel('案件名・テーマ').fill('F社 E2E案件')
await page.getByRole('button', { name: '追加する' }).click()
await page.waitForURL(/\/pipeline\/o-/)
await page.waitForSelector('.opp__title')
ok('受注見込み: 案件を追加すると詳細へ移動', (await page.locator('h1').innerText()).includes('F社 E2E案件'))
// 必要スキル → 役割
await page.getByLabel('スキルを追加').selectOption({ label: 'MES' })
await page.getByRole('button', { name: '役割を追加' }).click()
await page.waitForTimeout(200)
ok('案件詳細: 必要な役割と工数を入力できる / 必要スキルを選べる', (await page.locator('.dtable__row:not(.dtable__row--head)').count()) === 1 && (await page.locator('.skillreq').count()) === 1)
await page.locator('.dtable__row input[type=number]').fill('240')
await page.locator('.dtable__row input[type=number]').blur()
await page.waitForTimeout(200)
ok('案件詳細: 工数240h → 1.5人月・不足240h', (await main()).includes('1.5人月') && (await page.locator('.dtable__gap').innerText()).includes('不足 240h'))
await goto(page, '/pipeline')
ok('受注見込み: 追加した案件が「相談」列に出る', (await col('相談').locator('.ocard', { hasText: 'F社 E2E案件' }).count()) === 1)
// 段階の変更
await page.locator('.ocard', { hasText: 'F社 E2E案件' }).locator('select').selectOption('evaluation')
await page.waitForTimeout(250)
ok('受注見込み: 段階の選択で「評価中」へ移動し、確度が標準(70%)になる', (await col('評価中').locator('.ocard', { hasText: 'F社 E2E案件' }).count()) === 1 && (await page.locator('.ocard', { hasText: 'F社 E2E案件' }).locator('.ocard__prob').innerText()) === '70%')
// ドラッグ＆ドロップ
await page.locator('.ocard', { hasText: 'F社 E2E案件' }).dragTo(col('PJ候補'))
await page.waitForTimeout(300)
ok('受注見込み: ドラッグ＆ドロップで段階を移動', (await col('PJ候補').locator('.ocard', { hasText: 'F社 E2E案件' }).count()) === 1)
// 稼働状況の Expected が増える
await goto(page, '/workload')
const unassignedBefore = await page.locator('.wl__row--unassigned').innerText()
// 見送り
await goto(page, '/pipeline')
await page.locator('.ocard', { hasText: 'F社 E2E案件' }).getByRole('button', { name: '見送る' }).click()
await page.getByLabel('見送りの理由').fill('E2E: 体制確保できず')
await page.getByRole('button', { name: '見送る', exact: true }).last().click()
await page.waitForTimeout(300)
ok('受注見込み: 見送ると「PJ化済み・見送り」へ（理由つき）', (await page.locator('.closed li', { hasText: 'F社 E2E案件' }).innerText()).includes('体制確保できず'))

// ---------- PJ化評価 → PJ化 ----------
await goto(page, '/pipeline/o-e/evaluation')
const before = await page.locator('.evalresult__score').innerText()
ok('PJ化評価: 8軸のスコアと推奨表示', (await page.locator('.evalrow').count()) === 8 && /^\d+/.test(before))
await page.getByRole('radiogroup', { name: '顧客価値' }).getByRole('radio', { name: '1' }).click()
await page.getByRole('radiogroup', { name: '将来の継続性(LTV)' }).getByRole('radio', { name: '1' }).click()
await page.getByRole('radiogroup', { name: '戦略顧客性' }).getByRole('radio', { name: '1' }).click()
await page.waitForTimeout(250)
ok('PJ化評価: 点数を変えるとスコアが再計算される', (await page.locator('.evalresult__score').innerText()) !== before)
ok('PJ化評価: 「自動で可否は決まりません」の注記', (await page.locator('.evalresult').innerText()).includes('自動でPJ化の可否は決まりません'))
await page.getByRole('radiogroup', { name: '顧客価値' }).getByRole('radio', { name: '5' }).click()
await page.getByRole('button', { name: 'PJ化する' }).click()
await page.getByLabel('プロジェクト名').fill('E社 保全DX（E2E）')
await page.getByRole('button', { name: 'プロジェクトにする' }).click()
await page.waitForURL(/\/projects\/p-/)
await page.waitForSelector('.phead h1')
const pjUrl = page.url()
ok('PJ化: プロジェクトが作成される', (await page.locator('.phead h1').innerText()).includes('E社 保全DX（E2E）'))
await goto(page, new URL(pjUrl).pathname + '/wbs')
ok('PJ化: 標準WBS（164h）が入り、仮配置したメンバーが担当になる', (await page.locator('.wbs__row--total').innerText()).includes('164') && (await page.locator('.wbs__owner', { hasText: /Hさん|Uさん/ }).count()) >= 1)
await goto(page, '/pipeline')
ok('PJ化: 案件が「PJ化済み」になり、検討中から外れる', (await page.locator('.closed li', { hasText: '保全DX' }).count()) === 1 && (await page.locator('.board__col .ocard', { hasText: '保全DX' }).count()) === 0)

// ---------- 配置（Assignment Planner） ----------
await goto(page, '/assignments?target=opp:o-b')
ok('配置: 役割ごとの必要・配置済み・不足が出る', (await page.locator('.roles__item').count()) === 3 && (await main()).includes('不足'))
ok('配置: 候補が適合度順に並び、5つの内訳が出る', (await page.locator('.cand').count()) === 4 && (await page.locator('.cand').first().locator('.cand__bar').count()) === 5)
const matches = (await page.locator('.cand__match b').allInnerTexts()).map(Number)
ok('配置: 適合度は降順', matches.every((v, i) => i === 0 || matches[i - 1] >= v), matches.join())
const kW = await (async () => { await goto(page, '/workload'); return num(await page.getByRole('cell', { name: /Hさん \+3週/ }).getAttribute('aria-label').then((s) => s.match(/負荷(\d+)%/)[1])) })()
await goto(page, '/assignments?target=opp:o-b')
const hCand = page.locator('.cand', { hasText: 'Hさん' })
await hCand.getByRole('button', { name: '仮配置する…' }).click()
ok('配置: 仮配置の前に Workload Before/After が出る', (await hCand.locator('.ba__row').count()) === 3)
await hCand.locator('input[placeholder^="例: 構想コンサル"]').fill('E2E: 育成のため')
await hCand.getByRole('button', { name: /^仮配置する（/ }).click()
await page.waitForTimeout(300)
ok('配置: 仮配置が「配置の状況」に出る（仮・理由つき）', (await page.locator('.asg--full', { hasText: 'Hさん' }).innerText()).includes('E2E: 育成のため') && (await page.locator('.asg--full .chip--warn').count()) >= 1)
await goto(page, '/workload')
const kW2 = num(await page.getByRole('cell', { name: /Hさん \+3週/ }).getAttribute('aria-label').then((s) => s.match(/負荷(\d+)%/)[1]))
ok('配置: 仮配置すると稼働状況（見込み込み）の負荷率が上がる', kW2 >= kW, `${kW} -> ${kW2}`)
// 確定
await goto(page, '/assignments?target=opp:o-b')
await page.getByRole('button', { name: '確定する' }).first().click()
await page.waitForTimeout(250)
ok('配置: 課長（Kさん）が確定できる', (await page.locator('.asg--full .chip', { hasText: '確定' }).count()) >= 1)
// 過負荷の警告
await goto(page, '/assignments?target=opp:o-c')
await page.getByLabel('週あたりの時間').fill('40')
const kCand = page.locator('.cand', { hasText: 'Kさん' })
ok('配置: 100%を超えると警告（候補に注意）', (await kCand.innerText()).includes('100%を超える') || (await page.locator('.cand.is-over').count()) >= 1)
// 比較
await page.locator('.cand').nth(0).getByLabel(/を比較に加える/).check()
await page.locator('.cand').nth(1).getByLabel(/を比較に加える/).check()
ok('配置: 2名を選ぶと案の比較表が出る', (await page.locator('.cmp').count()) === 1)

// ---------- メンバー・スキルマップ ----------
await goto(page, '/people')
ok('メンバー: 4名のカード（負荷・来月の空き・スキル・育成テーマ・NEW）', (await page.locator('.pcard').count()) === 4 && (await page.locator('.pcard', { hasText: 'Hさん' }).locator('.badge-new').count()) === 1)
await page.locator('.pcard', { hasText: 'Hさん' }).click()
await page.waitForURL(/\/people\/u-h/)
const mesBefore = await page.getByLabel('MESのレベル').inputValue()
ok('プロフィール: スキル・経験・業界顧客・おすすめ・将来の空き・育成テーマ・履歴', (await main()).match(/スキル[\s\S]*プロジェクト経験[\s\S]*業界・顧客の経験[\s\S]*次におすすめ[\s\S]*将来の空き[\s\S]*育成テーマ[\s\S]*スキルの変更履歴/) !== null)
await page.getByRole('button', { name: /確認して確定/ }).click()
await page.locator('.explist__confirm label', { hasText: 'MES' }).locator('input').check()
await page.locator('.explist__confirm').getByRole('button', { name: '確定する' }).click()
await page.waitForTimeout(300)
const mesAfter = await page.getByLabel('MESのレベル').inputValue()
ok('プロフィール: 経験を確定してMESのレベルを+1 → スキルに反映', Number(mesAfter) === Number(mesBefore) + 1, `${mesBefore} -> ${mesAfter}`)
ok('プロフィール: スキルの変更履歴に残る', (await page.locator('.log').last().innerText()).includes('MES'))
await page.getByRole('textbox', { name: '育成テーマ' }).fill('E2E 育成テーマ')
await page.locator('.irisks__add').getByRole('button', { name: '追加' }).click()
ok('プロフィール: 育成テーマを追加できる', (await main()).includes('E2E 育成テーマ'))
await goto(page, '/people/skills')
ok('スキルマップ: スキル×メンバー表と目標人数・不足', (await page.locator('.smx tbody tr').count()) === 6 && (await page.locator('.smx tr.is-short').count()) >= 1)
const sel = page.getByLabel('Uさんのコンサルティングのレベル')
await sel.selectOption('4')
await page.waitForTimeout(200)
ok('スキルマップ: セルで直接レベルを変更できる', (await sel.inputValue()) === '4')
ok('スキルマップ: 育成の候補が出て、育成テーマにできる', (await page.locator('.gcand').count()) >= 1)

// ---------- プロジェクト完了 → 経験 ----------
await goto(page, '/projects/gtm/close')
await page.getByLabel('達成した成果').fill('E2E 完了')
await page.getByLabel('学び・振り返り').fill('E2E 学び')
await page.getByRole('button', { name: '完了して経験を記録する' }).click()
await page.getByRole('button', { name: '完了する', exact: true }).click()
await page.waitForTimeout(400)
ok('完了処理: 完了済みの表示と、メンバーへの導線', (await main()).includes('完了済みです') && (await page.locator('.rb a').count()) >= 1)
await goto(page, '/people/u-u')
ok('完了処理: メンバーの経験に「確認待ち」の候補ができる', (await page.locator('.explist .badge-new').count()) >= 1)
await goto(page, '/projects')
ok('完了処理: 完了したプロジェクトは既定の一覧から外れる', (await page.locator('a.pf__row', { hasText: '新商材GTM' }).count()) === 0)

// ---------- 管理 ----------
await goto(page, '/admin')
await page.getByLabel('Kさんの権限').selectOption('admin')
await page.getByRole('tab', { name: 'スキル' }).click()
await page.getByLabel('スキル名').last().fill('E2Eスキル')
await page.getByRole('button', { name: '追加', exact: true }).click()
await goto(page, '/people/skills')
ok('管理: スキルを追加するとスキルマップの行になる', (await page.locator('.smx tbody tr').count()) === 7)
await goto(page, '/admin')
await page.getByRole('tab', { name: '設定' }).click()
await page.getByLabel('工数入力の刻み').selectOption('0.25').catch(async () => page.locator('select').first().selectOption('0.25'))
await goto(page, '/my-work')
ok('管理: 工数入力の刻みを0.25hにすると My Work のステップが変わる', (await page.locator('.stepper button[aria-label="0.25h増やす"]').count()) >= 1)
await goto(page, '/')
const warnBefore = num(await page.locator('.kpi', { hasText: '過負荷の人数' }).locator('.kpi__value').innerText())
await goto(page, '/admin')
await page.getByRole('tab', { name: '設定' }).click()
await page.locator('.field', { hasText: '負荷「過負荷」の上限' }).locator('input').fill('80')
await page.locator('.field', { hasText: '負荷「過負荷」の上限' }).locator('input').blur()
await goto(page, '/')
const warnAfter = num(await page.locator('.kpi', { hasText: '過負荷の人数' }).locator('.kpi__value').innerText())
ok('管理: 過負荷のしきい値を下げると過負荷の人数が増える', warnAfter >= warnBefore && warnAfter >= 3, `${warnBefore} -> ${warnAfter}`)
await goto(page, '/admin')
await page.getByRole('tab', { name: '更新履歴' }).click()
ok('管理: 更新履歴（誰が・いつ・何を）', (await page.locator('.audit-cols:not(.admtable__row--head)').count()) > 10)
await page.getByRole('tab', { name: 'データ' }).click()
await page.getByRole('button', { name: /デモデータに初期化/ }).click()
await page.getByRole('button', { name: '初期化する' }).click()
await page.waitForTimeout(400)
await goto(page, '/projects')
ok('Reset: デモデータに戻る（追加したPJが消える）', (await page.locator('a.pf__row', { hasText: 'F社 E2E構想' }).count()) === 0 && (await page.locator('a.pf__row').count()) === 4)

// ---------- 権限 ----------
await switchUser(page, 'Sさん')
await goto(page, '/projects/bmes/wbs')
ok('権限(担当): 作業の追加・テンプレート・行メニューが出ない', (await page.getByRole('button', { name: '作業を追加' }).count()) === 0 && (await page.locator('.wbs__menu button').count()) === 0)
await page.locator('.wbs__row', { hasText: 'As-Is整理' }).click()
await page.waitForSelector('.drawer')
ok('権限(担当): 他人の作業は参照のみ（保存できない）', (await page.locator('.drawer').innerText()).includes('参照のみ') && (await page.getByRole('button', { name: '保存', exact: true }).isDisabled()))
await page.keyboard.press('Escape')
await goto(page, '/')
ok('権限(担当): ナビに「管理」が出ない', (await page.locator('.sidebar').getByText('管理', { exact: true }).count()) === 0)
await goto(page, '/admin')
ok('権限(担当): /admin は案内のみ', (await main()).includes('管理者のみ'))
await goto(page, '/pipeline')
ok('権限(担当): 案件を追加できない', (await page.getByRole('button', { name: '案件を追加' }).count()) === 0 && (await page.locator('.ocard select').count()) === 0)
await goto(page, '/pipeline/o-c/evaluation')
ok('権限(担当): PJ化の判断ができない', (await page.getByRole('button', { name: 'PJ化する' }).count()) === 0)
await goto(page, '/assignments?target=opp:o-b')
ok('権限(担当): 仮配置できない（推薦は見える）', (await page.getByRole('button', { name: '仮配置する…' }).count()) === 0 && (await page.locator('.cand').count()) === 4)
await goto(page, '/people/u-s')
ok('権限(担当): 自分のスキルは変更できる', (await page.getByLabel('顧客折衝のレベル').count()) === 1)
await goto(page, '/people/u-h')
ok('権限(担当): 他人のスキルは変更できない', (await page.getByLabel('MESのレベル').count()) === 0)
await switchUser(page, 'Hさん')
await goto(page, '/projects/asaas/wbs')
ok('権限(リーダー): 自分がリーダーでないPJは構成を変更できない', (await page.getByRole('button', { name: '作業を追加' }).count()) === 0)
await goto(page, '/projects/bmes/wbs')
ok('権限(リーダー): 自分のPJは変更できる', (await page.getByRole('button', { name: '作業を追加' }).count()) >= 1)
await goto(page, '/pipeline')
ok('権限(リーダー): 案件の追加は課長以上', (await page.getByRole('button', { name: '案件を追加' }).count()) === 0)

process.exitCode = summary(errs) ? 1 : 0
await browser.close()
